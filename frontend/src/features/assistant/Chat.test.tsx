import { render, screen, waitFor, within } from '@testing-library/react';
import userEvent from '@testing-library/user-event';
import { http, HttpResponse } from 'msw';
import { useState } from 'react';
import { MemoryRouter } from 'react-router-dom';
import { server } from '../../test/handlers';
import { openSseResponse, sseEvent, sseResponse } from '../../test/sse';
import { withQueryClient } from '../../test/withQueryClient';
import { Chat } from './Chat';

const answer = (...events: Record<string, unknown>[]): void => {
  server.use(
    http.post('/api/assistant/messages', () =>
      sseResponse(...events.map((e) => sseEvent(e as { type: string }))),
    ),
  );
};

interface HarnessProps {
  readonly operator?: boolean;
  readonly quickEnabled?: boolean;
  readonly aiEnabled?: boolean;
}

function Harness({ operator = false, quickEnabled, aiEnabled }: HarnessProps): React.JSX.Element {
  const [draft, setDraft] = useState('');
  return (
    <Chat
      onSaved={() => undefined}
      operator={operator}
      draft={draft}
      onDraftChange={setDraft}
      quickEnabled={quickEnabled}
      aiEnabled={aiEnabled}
    />
  );
}

function renderWith(props: HarnessProps): void {
  render(
    <MemoryRouter>
      <Harness {...props} />
    </MemoryRouter>,
    { wrapper: withQueryClient() },
  );
}

function renderChat(operator = false): void {
  render(<Harness operator={operator} />, { wrapper: withQueryClient() });
}

async function ask(question: string): Promise<void> {
  const user = userEvent.setup();
  await user.type(await screen.findByRole('textbox', { name: 'Your question' }), question);
  await user.click(screen.getByRole('button', { name: 'Send' }));
}

describe('AssistantPage', () => {
  it('shows the note that answers must be checked', async () => {
    renderChat();

    expect(
      await screen.findByText(
        'Answers are generated by Claude from your data. Check before acting.',
      ),
    ).toBeInTheDocument();
  });

  it('streams the answer in, with a chip for each tool and no trace of the keep-alive', async () => {
    server.use(
      http.post('/api/assistant/messages', () =>
        sseResponse(
          sseEvent({ type: 'tool', tool: 'job_health' }),
          ': keep-alive\n\n',
          sseEvent({ type: 'text', delta: 'Nothing ' }),
          sseEvent({ type: 'text', delta: 'failed.' }),
          sseEvent({ type: 'done', conversationId: 'c-1', outcome: 'Answered' }),
        ),
      ),
    );
    renderChat();

    await ask('Did jobs fail?');

    const log = screen.getByRole('log', { name: 'Conversation' });
    expect(await within(log).findByText('Nothing failed.')).toBeInTheDocument();
    expect(within(log).getByRole('list', { name: 'Tools used' })).toHaveTextContent(
      'Checked job health',
    );
    expect(log).not.toHaveTextContent('keep-alive');
  });

  it('sends the conversation id with a follow-up', async () => {
    const bodies: unknown[] = [];
    server.use(
      http.post('/api/assistant/messages', async ({ request }) => {
        bodies.push(await request.json());
        return sseResponse(
          sseEvent({ type: 'text', delta: 'ok' }),
          sseEvent({ type: 'done', conversationId: 'c-9', outcome: 'Answered' }),
        );
      }),
    );
    renderChat();

    await ask('One?');
    await screen.findByText('ok');
    await ask('Two?');

    await waitFor(() => {
      expect(screen.getAllByText('ok')).toHaveLength(2);
    });
    expect(bodies).toEqual([
      { conversationId: null, question: 'One?' },
      { conversationId: 'c-9', question: 'Two?' },
    ]);
  });

  it('shows the error when the answer fails part-way', async () => {
    answer(
      { type: 'text', delta: 'Start' },
      {
        type: 'error',
        problem: {
          status: 503,
          title: 'assistant.unavailable',
          detail: 'The assistant is unavailable. Try again shortly.',
        },
      },
    );
    renderChat();

    await ask('Why?');

    expect(await screen.findByText(/The assistant is unavailable/)).toBeInTheDocument();
  });

  it('tells the admin to wait when the hourly limit is reached', async () => {
    server.use(
      http.post('/api/assistant/messages', () =>
        HttpResponse.json({ status: 429, title: 'Too Many Requests' }, { status: 429 }),
      ),
    );
    renderChat();

    await ask('Why?');

    expect(
      await screen.findByText("You've asked a lot in the last hour — try again later."),
    ).toBeInTheDocument();
  });

  it('stops an answer, then lets the next question continue the conversation', async () => {
    const bodies: unknown[] = [];
    let call = 0;
    server.use(
      http.post('/api/assistant/messages', async ({ request }) => {
        bodies.push(await request.json());
        call += 1;
        return call === 1
          ? sseResponse(
              sseEvent({ type: 'text', delta: 'first' }),
              sseEvent({ type: 'done', conversationId: 'c-5', outcome: 'Answered' }),
            )
          : call === 2
            ? openSseResponse(sseEvent({ type: 'text', delta: 'Still writing' }))
            : sseResponse(
                sseEvent({ type: 'text', delta: 'third' }),
                sseEvent({ type: 'done', conversationId: 'c-5', outcome: 'Answered' }),
              );
      }),
    );
    renderChat();
    const user = userEvent.setup();

    await ask('One?');
    await screen.findByText('first');
    await ask('Two?');
    await screen.findByText('Still writing');
    await user.click(screen.getByRole('button', { name: 'Stop' }));

    expect(await screen.findByText('Stopped.')).toBeInTheDocument();
    expect(screen.getByRole('textbox', { name: 'Your question' })).toBeEnabled();
    await ask('Three?');
    await screen.findByText('third');
    expect(bodies[2]).toEqual({ conversationId: 'c-5', question: 'Three?' });
  });

  it('puts the question back in the box when it could not be asked', async () => {
    server.use(
      http.post('/api/assistant/messages', () =>
        HttpResponse.json({ status: 429, title: 'Too Many Requests' }, { status: 429 }),
      ),
    );
    renderChat();

    await ask('Why did the export fail?');

    await screen.findByText("You've asked a lot in the last hour — try again later.");
    expect(screen.getByRole('textbox', { name: 'Your question' })).toHaveValue(
      'Why did the export fail?',
    );
  });

  it('says the assistant is thinking until the first words arrive', async () => {
    server.use(http.post('/api/assistant/messages', () => openSseResponse(': keep-alive\n\n')));
    renderChat();

    await ask('Why?');

    expect(await screen.findByRole('status')).toHaveTextContent('Thinking…');
  });

  it('keeps streaming when Ask is double-clicked', async () => {
    let calls = 0;
    server.use(
      http.post('/api/assistant/messages', () => {
        calls += 1;
        return openSseResponse(sseEvent({ type: 'text', delta: 'Still writing' }));
      }),
    );
    renderChat();
    const user = userEvent.setup();

    await user.type(await screen.findByRole('textbox', { name: 'Your question' }), 'Why?');
    await user.dblClick(screen.getByRole('button', { name: 'Send' }));

    await screen.findByText('Still writing');
    expect(screen.getByRole('button', { name: 'Stop' })).toBeInTheDocument();
    expect(calls).toBe(1);
  });

  it('greets an empty chat with suggestions that fill the composer', async () => {
    renderChat();
    const user = userEvent.setup();

    expect(screen.getByRole('heading', { name: 'How can I help you today?' })).toBeInTheDocument();
    await user.click(screen.getByRole('button', { name: 'Where is my latest order?' }));

    expect(screen.getByRole('textbox', { name: 'Your question' })).toHaveValue('Where is my latest order?');
  });

  it('suggests a monitoring question only to an operator', () => {
    renderChat(true);

    expect(screen.getByRole('button', { name: 'Did any background job fail today?' })).toBeInTheDocument();
  });

  it('sends on Enter', async () => {
    answer({ type: 'text', delta: 'Sent.' }, { type: 'done', conversationId: 'c-1', outcome: 'Answered' });
    renderChat();
    const user = userEvent.setup();

    await user.type(screen.getByRole('textbox', { name: 'Your question' }), 'Why?{Enter}');

    expect(await screen.findByText('Sent.')).toBeInTheDocument();
  });

  it('starts a new line on Shift+Enter instead of sending', async () => {
    renderChat();
    const user = userEvent.setup();
    const box = screen.getByRole('textbox', { name: 'Your question' });

    await user.type(box, 'One{Shift>}{Enter}{/Shift}Two');

    expect(box).toHaveValue('One\nTwo');
    expect(screen.queryByRole('log', { name: 'Conversation' })).not.toBeInTheDocument();
  });

  it('keeps Send disabled for a blank question', async () => {
    renderChat();

    await userEvent.type(screen.getByRole('textbox', { name: 'Your question' }), '   ');

    expect(screen.getByRole('button', { name: 'Send' })).toBeDisabled();
  });

  it('renders an answer as Markdown', async () => {
    answer({ type: 'text', delta: '- **one**\n- two' }, { type: 'done', conversationId: 'c-1', outcome: 'Answered' });
    renderChat();

    await ask('List?');

    expect((await screen.findByText('two')).tagName).toBe('LI');
    expect(screen.getByText('one').tagName).toBe('STRONG');
  });

  it('labels a member tool chip in words', async () => {
    answer(
      { type: 'tool', tool: 'my_orders' },
      { type: 'text', delta: 'None open.' },
      { type: 'done', conversationId: 'c-1', outcome: 'Answered' },
    );
    renderChat();

    await ask('Orders?');

    expect(await screen.findByRole('list', { name: 'Tools used' })).toHaveTextContent('Checked your orders');
  });

  it('shows the character count only near the limit', async () => {
    renderChat();
    const box = screen.getByRole('textbox', { name: 'Your question' });

    await userEvent.click(box);
    await userEvent.paste('x'.repeat(1801));

    expect(screen.getByText('1801 / 2000')).toBeInTheDocument();
  });
});

describe('instant answers', () => {
  it('asks the quick endpoint when instant answers are on, and shows the card', async () => {
    server.use(
      http.post('/api/assistant/quick', () =>
        sseResponse(
          sseEvent({ type: 'answer', answer: { kind: 'Instant', text: 'You have no orders yet.', facts: [], link: { label: 'Place an order', to: '/orders/new' } } }),
          sseEvent({ type: 'done', conversationId: 'c1', outcome: 'Answered' }),
        ),
      ),
    );
    renderWith({ quickEnabled: true, aiEnabled: false });

    await ask('Has my last order shipped?');

    expect(await screen.findByRole('article', { name: 'Instant answer' })).toHaveTextContent('You have no orders yet.');
  });

  it('asks a suggestion instantly, and the AI only when asked', async () => {
    const quick: string[] = [];
    const ai: string[] = [];
    server.use(
      http.post('/api/assistant/quick', async ({ request }) => {
        quick.push(((await request.json()) as { question: string }).question);
        return sseResponse(
          sseEvent({ type: 'suggestions', suggestions: { text: "I'm not sure what you mean.", options: ['Is my export ready?'], aiAvailable: true } }),
          sseEvent({ type: 'done', conversationId: 'c1', outcome: 'Answered' }),
        );
      }),
      http.post('/api/assistant/messages', async ({ request }) => {
        ai.push(((await request.json()) as { question: string }).question);
        return sseResponse(sseEvent({ type: 'text', delta: 'A poem.' }), sseEvent({ type: 'done', conversationId: 'c1', outcome: 'Answered' }));
      }),
    );
    renderWith({ quickEnabled: true, aiEnabled: true });

    await ask('Write me a poem');
    await userEvent.click(await screen.findByRole('button', { name: 'Is my export ready?' }));
    const [askAi] = await screen.findAllByRole('button', { name: /Ask the AI/ });
    if (askAi === undefined) {
      throw new Error('Ask the AI was not offered');
    }
    await userEvent.click(askAi);

    await waitFor(() => {
      expect(ai).toEqual(['Write me a poem']);
    });
    expect(quick).toEqual(['Write me a poem', 'Is my export ready?']);
  });

  it('hides Ask the AI when the AI is off', async () => {
    server.use(
      http.post('/api/assistant/quick', () =>
        sseResponse(
          sseEvent({ type: 'suggestions', suggestions: { text: "I'm not sure what you mean.", options: [], aiAvailable: false } }),
          sseEvent({ type: 'done', conversationId: 'c1', outcome: 'Answered' }),
        ),
      ),
    );
    renderWith({ quickEnabled: true, aiEnabled: false });

    await ask('Write me a poem');

    expect(await screen.findByText("I'm not sure what you mean.")).toBeInTheDocument();
    expect(screen.queryByRole('button', { name: /Ask the AI/ })).not.toBeInTheDocument();
  });
});
