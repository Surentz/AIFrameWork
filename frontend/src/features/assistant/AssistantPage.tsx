import { useState } from 'react';
import type { SubmitEvent } from 'react';
import { ApiError } from '../../api/client';
import { ErrorPanel } from '../../components/ErrorPanel';
import type { AssistantMessage } from './conversation';
import { useAssistantStatus } from './queries';
import { useAssistantConversation } from './useAssistantConversation';
import './assistant.css';

const MaxQuestionLength = 2000;

/** What each tool looked at, in the words the chip shows. */
const toolLabels: Readonly<Record<string, string>> = {
  job_health: 'job health',
  list_job_runs: 'job runs',
  get_job_run: 'a job run',
  list_dead_letters: 'dead letters',
  traffic_summary: 'traffic',
  traffic_series: 'traffic over time',
  external_systems: 'external systems',
  sign_in_health: 'sign-ins',
};

/**
 * The ops assistant (ADR 0033): questions about the monitoring data, answered by Claude as a
 * stream. Admin-only by its route; hidden entirely when the assistant is switched off.
 */
export function AssistantPage(): React.JSX.Element {
  const status = useAssistantStatus();

  if (status.isPending) {
    return <p role="status">Loading the assistant…</p>;
  }

  if (status.error) {
    return <ErrorPanel error={status.error} />;
  }

  if (!status.data.enabled) {
    return (
      <section>
        <h1>Ask the assistant</h1>
        <p>
          The assistant is switched off. An operator turns it on with{' '}
          <code>Assistant__Enabled</code> and an API key file; see{' '}
          <code>docs/local-development.md</code>.
        </p>
      </section>
    );
  }

  return <AssistantChat />;
}

function AssistantChat(): React.JSX.Element {
  const conversation = useAssistantConversation();
  const [question, setQuestion] = useState('');
  const trimmed = question.trim();

  function submit(event: SubmitEvent<HTMLFormElement>): void {
    event.preventDefault();
    if (trimmed === '' || conversation.streaming) {
      return;
    }

    setQuestion('');
    void conversation.ask(trimmed).then((outcome) => {
      // Nothing was saved for a failed question, so put it back: asking again needs no retyping.
      if (outcome === 'failed') {
        setQuestion(trimmed);
      }
    });
  }

  return (
    <section className="assistant">
      <h1>Ask the assistant</h1>
      <p className="muted">
        Answers are generated by Claude from monitoring data. Check before acting.
      </p>

      <ol
        className="assistant-log"
        aria-label="Conversation"
        role="log"
        aria-busy={conversation.streaming}
      >
        {conversation.messages.map((message, index) => (
          <Message
            key={message.id}
            message={message}
            thinking={
              conversation.streaming &&
              index === conversation.messages.length - 1 &&
              message.text === ''
            }
          />
        ))}
      </ol>

      {conversation.error && <AssistantError error={conversation.error} />}

      <form className="assistant-form" onSubmit={submit}>
        <label htmlFor="assistant-question">Your question</label>
        <textarea
          id="assistant-question"
          value={question}
          maxLength={MaxQuestionLength}
          rows={3}
          disabled={conversation.streaming}
          onChange={(event) => {
            setQuestion(event.target.value);
          }}
        />
        <p className="muted">
          {question.length} / {MaxQuestionLength}
        </p>
        <div className="assistant-form__actions">
          {/* Ask stays put, disabled while streaming, and Stop is a button of its own. Swapping one
              for the other in place reuses the DOM node, so a double-click on Ask stopped the
              question it had just asked. */}
          <button type="submit" disabled={trimmed === '' || conversation.streaming}>
            Ask
          </button>
          {conversation.streaming && (
            <button type="button" onClick={conversation.stop}>
              Stop
            </button>
          )}
          <button
            type="button"
            onClick={conversation.startOver}
            disabled={conversation.messages.length === 0}
          >
            New conversation
          </button>
        </div>
      </form>
    </section>
  );
}

interface MessageProps {
  readonly message: AssistantMessage;
  /** Still streaming with no words yet: the model can think for a minute before its first one. */
  readonly thinking: boolean;
}

function Message({ message, thinking }: MessageProps): React.JSX.Element {
  return (
    <li className={`assistant-message assistant-message--${message.role}`}>
      <span className="assistant-message__who">
        {message.role === 'user' ? 'You' : 'Assistant'}
      </span>
      {message.tools.length > 0 && (
        <ul className="assistant-tools" aria-label="Tools used">
          {message.tools.map((tool, index) => (
            // A tool can be used twice in one answer, so its position is part of its key; the list
            // only ever grows at its end, so positions never shift.
            <li key={`${tool}-${String(index)}`}>Checked {toolLabels[tool] ?? tool}</li>
          ))}
        </ul>
      )}
      {thinking && (
        <p className="muted" role="status">
          Thinking…
        </p>
      )}
      <p className="assistant-message__text">{message.text}</p>
      {message.stopped && <p className="muted">Stopped.</p>}
      {message.outcome === 'Capped' && (
        <p className="muted">The assistant reached its step limit and answered with what it had.</p>
      )}
      {message.outcome === 'Truncated' && <p className="muted">This answer was cut short.</p>}
    </li>
  );
}

interface AssistantErrorProps {
  readonly error: Error;
}

function AssistantError({ error }: AssistantErrorProps): React.JSX.Element {
  if (error instanceof ApiError && error.status === 429) {
    return <p role="alert">You've asked a lot in the last hour — try again later.</p>;
  }

  return <ErrorPanel error={error} />;
}
