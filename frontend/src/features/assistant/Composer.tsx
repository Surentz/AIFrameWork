import type { KeyboardEvent, SubmitEvent } from 'react';

export const MaxQuestionLength = 2000;

/** The counter appears only when it matters. */
const CountFrom = 1800;

interface ComposerProps {
  readonly value: string;
  readonly onChange: (value: string) => void;
  readonly onSend: () => void;
  readonly onStop: () => void;
  readonly streaming: boolean;
  readonly placeholder: string;
}

/**
 * The input pinned under the chat. Enter sends; Shift+Enter (or Enter while an IME is composing)
 * is a newline. Send stays in place, disabled while an answer streams, and Stop appears beside it:
 * a button that changed into Stop under the pointer let a double-click stop what it just sent.
 */
export function Composer({
  value,
  onChange,
  onSend,
  onStop,
  streaming,
  placeholder,
}: ComposerProps): React.JSX.Element {
  const blank = value.trim() === '';

  function submit(event: SubmitEvent<HTMLFormElement>): void {
    event.preventDefault();
    if (!blank && !streaming) {
      onSend();
    }
  }

  function sendOnEnter(event: KeyboardEvent<HTMLTextAreaElement>): void {
    if (event.key === 'Enter' && !event.shiftKey && !event.nativeEvent.isComposing) {
      event.preventDefault();
      event.currentTarget.form?.requestSubmit();
    }
  }

  return (
    <div className="assistant-composer-wrap">
      <form className="assistant-composer" onSubmit={submit}>
        <label htmlFor="assistant-question" className="visually-hidden">
          Your question
        </label>
        <textarea
          id="assistant-question"
          className="assistant-composer__input"
          value={value}
          maxLength={MaxQuestionLength}
          rows={1}
          placeholder={placeholder}
          disabled={streaming}
          onChange={(event) => {
            onChange(event.target.value);
          }}
          onKeyDown={sendOnEnter}
        />
        {streaming && (
          <button type="button" className="assistant-composer__stop" aria-label="Stop" onClick={onStop}>
            <svg viewBox="0 0 24 24" width="14" height="14" aria-hidden="true">
              <rect x="6" y="6" width="12" height="12" rx="2" fill="currentColor" />
            </svg>
          </button>
        )}
        <button type="submit" className="assistant-composer__send" aria-label="Send" disabled={blank || streaming}>
          <svg viewBox="0 0 24 24" width="16" height="16" fill="none" stroke="currentColor"
            strokeWidth="2.2" strokeLinecap="round" strokeLinejoin="round" aria-hidden="true">
            <path d="M12 19V5M5 12l7-7 7 7" />
          </svg>
        </button>
      </form>
      {value.length > CountFrom && (
        <p className="assistant-composer__count">
          {value.length} / {MaxQuestionLength}
        </p>
      )}
      <p className="assistant-note">Answers are generated by Claude from your data. Check before acting.</p>
    </div>
  );
}
