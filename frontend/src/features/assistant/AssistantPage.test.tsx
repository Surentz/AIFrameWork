import { render, screen, within } from '@testing-library/react';
import userEvent from '@testing-library/user-event';
import { http, HttpResponse } from 'msw';
import { MemoryRouter } from 'react-router-dom';
import { server } from '../../test/handlers';
import { openSseResponse, sseEvent, sseResponse } from '../../test/sse';
import { withQueryClient } from '../../test/withQueryClient';
import { AssistantPage } from './AssistantPage';

const answer = (...events: Record<string, unknown>[]): void => {
  server.use(
    http.post('/api/assistant/messages', () =>
      sseResponse(...events.map((e) => sseEvent(e as { type: string }))),
    ),
  );
};

function renderPage(enabled = true): void {
  server.use(http.get('/api/assistant', () => HttpResponse.json({ enabled })));
  render(
    <MemoryRouter>
      <AssistantPage />
    </MemoryRouter>,
    { wrapper: withQueryClient() },
  );
}

async function ask(question: string): Promise<void> {
  const user = userEvent.setup();
  await user.type(await screen.findByRole('textbox', { name: 'Your question' }), question);
  await user.click(screen.getByRole('button', { name: 'Ask' }));
}

describe('AssistantPage', () => {
  it('says the assistant is switched off when it is', async () => {
    renderPage(false);

    expect(await screen.findByText(/The assistant is switched off/)).toBeInTheDocument();
    expect(screen.queryByRole('textbox', { name: 'Your question' })).not.toBeInTheDocument();
  });

  it('shows the note that answers must be checked', async () => {
    renderPage();

    expect(
      await screen.findByText('Answers are generated by Claude from monitoring data. Check before acting.'),
    ).toBeInTheDocument();
  });

  it('streams the answer in, with a chip for each tool and no trace of the keep-alive', async () => {
    server.use(
      http.post('/api/assistant/messages', () =>
        sseResponse(
          sseEvent({ type: 'tool', tool: 'job_health' }),
          ': keep-alive\n\n',
          sseEvent({ type: 'text', delta: 'Nothing ' }),
          sseEvent({ type: 'text', delta: 'failed.' }),
          sseEvent({ type: 'done', conversationId: 'c-1', outcome: 'Answered' }),
        ),
      ),
    );
    renderPage();

    await ask('Did jobs fail?');

    const log = screen.getByRole('log', { name: 'Conversation' });
    expect(await within(log).findByText('Nothing failed.')).toBeInTheDocument();
    expect(within(log).getByRole('list', { name: 'Tools used' })).toHaveTextContent('Checked job health');
    expect(log).not.toHaveTextContent('keep-alive');
  });

  it('sends the conversation id with a follow-up', async () => {
    const bodies: unknown[] = [];
    server.use(
      http.post('/api/assistant/messages', async ({ request }) => {
        bodies.push(await request.json());
        return sseResponse(
          sseEvent({ type: 'text', delta: 'ok' }),
          sseEvent({ type: 'done', conversationId: 'c-9', outcome: 'Answered' }),
        );
      }),
    );
    renderPage();

    await ask('One?');
    await screen.findByText('ok');
    await ask('Two?');

    await screen.findAllByText('ok');
    expect(bodies).toEqual([
      { conversationId: null, question: 'One?' },
      { conversationId: 'c-9', question: 'Two?' },
    ]);
  });

  it('shows the error when the answer fails part-way', async () => {
    answer(
      { type: 'text', delta: 'Start' },
      { type: 'error', problem: { status: 503, title: 'assistant.unavailable', detail: 'The assistant is unavailable. Try again shortly.' } },
    );
    renderPage();

    await ask('Why?');

    expect(await screen.findByText(/The assistant is unavailable/)).toBeInTheDocument();
  });

  it('tells the admin to wait when the hourly limit is reached', async () => {
    server.use(
      http.post('/api/assistant/messages', () =>
        HttpResponse.json({ status: 429, title: 'Too Many Requests' }, { status: 429 }),
      ),
    );
    renderPage();

    await ask('Why?');

    expect(await screen.findByText("You've asked a lot in the last hour — try again later.")).toBeInTheDocument();
  });

  it('stops an answer, then lets the next question continue the conversation', async () => {
    const bodies: unknown[] = [];
    let call = 0;
    server.use(
      http.post('/api/assistant/messages', async ({ request }) => {
        bodies.push(await request.json());
        call += 1;
        return call === 1
          ? sseResponse(sseEvent({ type: 'text', delta: 'first' }), sseEvent({ type: 'done', conversationId: 'c-5', outcome: 'Answered' }))
          : call === 2
            ? openSseResponse(sseEvent({ type: 'text', delta: 'Still writing' }))
            : sseResponse(sseEvent({ type: 'text', delta: 'third' }), sseEvent({ type: 'done', conversationId: 'c-5', outcome: 'Answered' }));
      }),
    );
    renderPage();
    const user = userEvent.setup();

    await ask('One?');
    await screen.findByText('first');
    await ask('Two?');
    await screen.findByText('Still writing');
    await user.click(screen.getByRole('button', { name: 'Stop' }));

    expect(await screen.findByText('Stopped.')).toBeInTheDocument();
    expect(screen.getByRole('textbox', { name: 'Your question' })).toBeEnabled();
    await ask('Three?');
    await screen.findByText('third');
    expect(bodies[2]).toEqual({ conversationId: 'c-5', question: 'Three?' });
  });

  it('recovers from an expired conversation with New conversation', async () => {
    const bodies: unknown[] = [];
    let call = 0;
    server.use(
      http.post('/api/assistant/messages', async ({ request }) => {
        bodies.push(await request.json());
        call += 1;
        if (call === 1) {
          return sseResponse(sseEvent({ type: 'text', delta: 'first' }), sseEvent({ type: 'done', conversationId: 'gone', outcome: 'Answered' }));
        }
        return call === 2
          ? HttpResponse.json(
              { status: 404, title: 'assistant.conversation_not_found', detail: 'That conversation does not exist or has expired. Start a new one.' },
              { status: 404 },
            )
          : sseResponse(sseEvent({ type: 'text', delta: 'fresh' }), sseEvent({ type: 'done', conversationId: 'new', outcome: 'Answered' }));
      }),
    );
    renderPage();
    const user = userEvent.setup();

    await ask('One?');
    await screen.findByText('first');
    await ask('Two?');
    expect(await screen.findByText(/has expired/)).toBeInTheDocument();
    await user.click(screen.getByRole('button', { name: 'New conversation' }));
    await ask('Three?');

    await screen.findByText('fresh');
    expect(bodies[2]).toEqual({ conversationId: null, question: 'Three?' });
  });

  it('keeps Ask disabled for a blank question', async () => {
    renderPage();
    const user = userEvent.setup();

    await user.type(await screen.findByRole('textbox', { name: 'Your question' }), '   ');

    expect(screen.getByRole('button', { name: 'Ask' })).toBeDisabled();
  });
});
